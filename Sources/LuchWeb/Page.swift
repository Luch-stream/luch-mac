        "        var units = nals(data);",
        "        for (var i = 0; i < units.length; i++) {",
        "            var type = units[i][0] & 0x1f;",
        "            if (type === 7) sps = units[i];",
        "            if (type === 8) pps = units[i];",
        "        }",
        "    }",
        "    if (!sps || !pps) return;",
        "    var sample = avccSample(data);",
        "    if (!initDone) {",
        "        mime = 'video/mp4; codecs=\"avc1.' +",
        "            [sps[1], sps[2], sps[3]].map(function (x) { return ('0' + x.toString(16)).slice(-2); }).join('') + '\"';",
        "        buildSource();",
        "        initDone = true;",
        "    }",
        "    if (pending) {",
        "        appendFragment(pending.pts, Math.max(1, Math.min(9000, pts - pending.pts)), pending.sample);",
        "    }",
        "    pending = { pts: pts * timescale / 1000000, sample: sample };",
        "    frames++;",
        "}",
        "",
        "function buildSource() {",
        "    ms = new MediaSource();",
        "    $('v').src = URL.createObjectURL(ms);",
        "    ms.addEventListener('sourceopen', function () {",
        "        sb = ms.addSourceBuffer(mime);",
        "        sb.mode = 'segments';",
        "        sb.addEventListener('updateend', drain);",
        "        append(initSegment(videoWidth(), videoHeight()));",
        "    });",
        "}",
        "",
        "function videoWidth() { return screen.width; }",
        "function videoHeight() { return screen.height; }",
        "",
        "function append(data) { queue.push(data); drain(); }",
        "function appendFragment(pts, duration, sample) {",
        "    append(fragment(Math.round(pts), duration, sample));",
        "}",
        "function drain() {",
        "    if (!sb || sb.updating || !queue.length) return;",
        "    sb.appendBuffer(queue.shift());",
        "    // keep only the last seconds: a live stream must not grow a buffer forever",
        "    try {",
        "        var start = sb.buffered.start(0), end = sb.buffered.end(0);",
        "        if (end - start > 6) sb.remove(start, end - 4);",
        "        if (end - $('v').currentTime > 2) $('v').currentTime = end - 0.3;",
        "    } catch (e) {}",
        "}",
        "",
        "$('go').onclick = start;",
        "document.body.ondblclick = function () {",
        "    if (document.fullscreenElement) document.exitFullscreen();",
        "    else document.documentElement.requestFullscreen && document.documentElement.requestFullscreen();",
        "};",
        "</script>",
        "</html>",
        "",
    ].joined(separator: "\n")
